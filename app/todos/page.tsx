import { createClient } from '@/utils/supabase/server';
import { cookies } from 'next/headers';
import Link from 'next/link';
import { ArrowLeft, CheckCircle2, AlertCircle, Database, Plus } from 'lucide-react';

export default async function TodosPage() {
  const cookieStore = cookies();
  const supabase = createClient(cookieStore);

  const { data: todos, error } = await supabase.from('todos').select();

  return (
    <div className="min-h-screen bg-clay-canvas text-clay-text flex flex-col items-center justify-start py-12 px-4">
      <div className="w-full max-w-xl bg-white border border-clay-border/80 rounded-clay shadow-clay-card p-6 space-y-6">
        {/* Top Header */}
        <div className="flex items-center justify-between border-b border-clay-border/70 pb-4">
          <Link
            href="/"
            className="flex items-center gap-1.5 text-xs font-semibold text-accent-blue hover:underline bg-blue-50 px-3 py-1.5 rounded-clay-sm border border-blue-100"
          >
            <ArrowLeft className="w-3.5 h-3.5" /> Back to Business Radar
          </Link>
          <div className="flex items-center gap-2 text-xs font-medium text-emerald-700 bg-emerald-50 px-2.5 py-1 rounded-full border border-emerald-200">
            <CheckCircle2 className="w-3.5 h-3.5" /> Supabase SSR Connected
          </div>
        </div>

        {/* Title */}
        <div className="space-y-1">
          <div className="flex items-center gap-2">
            <Database className="w-5 h-5 text-accent-blue" />
            <h1 className="text-xl font-bold tracking-tight">Supabase SSR Todos</h1>
          </div>
          <p className="text-xs text-clay-muted">
            Live query executed via Server Component (<code className="font-mono bg-slate-100 px-1 py-0.5 rounded">utils/supabase/server.ts</code>)
          </p>
        </div>

        {/* Error or Table missing alert */}
        {error ? (
          <div className="p-4 rounded-clay-sm bg-amber-50 border border-amber-200 text-amber-900 text-xs space-y-2">
            <div className="flex items-center gap-2 font-semibold">
              <AlertCircle className="w-4 h-4 text-amber-600" />
              <span>Query result: {error.message}</span>
            </div>
            <p className="leading-relaxed text-amber-800">
              Your Supabase client is connected! To display records here, create the <code className="font-mono bg-white px-1 py-0.5 rounded border border-amber-300">todos</code> table in your Supabase SQL editor:
            </p>
            <pre className="p-2.5 bg-white/80 rounded font-mono text-[11px] overflow-x-auto border border-amber-200 text-slate-800">
{`CREATE TABLE todos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  is_complete BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);`}
            </pre>
          </div>
        ) : (
          <div className="space-y-3">
            <div className="flex items-center justify-between text-xs text-clay-muted">
              <span>Items in table: <strong>{todos?.length ?? 0}</strong></span>
            </div>

            {todos && todos.length > 0 ? (
              <ul className="divide-y divide-clay-border/60 border border-clay-border/80 rounded-clay-sm overflow-hidden bg-slate-50/50">
                {todos.map((todo: any) => (
                  <li key={todo.id} className="p-3 flex items-center justify-between text-sm bg-white hover:bg-slate-50">
                    <span className="font-medium text-slate-800">{todo.name}</span>
                    <span className="text-[11px] font-mono text-clay-muted">ID: {todo.id}</span>
                  </li>
                ))}
              </ul>
            ) : (
              <div className="text-center py-8 px-4 rounded-clay-sm bg-slate-50 border border-dashed border-slate-300 text-xs text-clay-muted space-y-1">
                <p className="font-semibold text-slate-700">No todos found in table</p>
                <p>Insert a record in your Supabase table editor to view it here.</p>
              </div>
            )}
          </div>
        )}
      </div>
    </div>
  );
}
